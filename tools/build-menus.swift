import Foundation
import PDFKit
import AppKit

// Renders the menu PDFs in menus/source/ into web images, then rewrites the
// menu viewer markup in food-and-drink.html to match.
//
// Driven entirely by menus/menus.json — to change what the site shows, edit
// that file (or drop in a replacement PDF) and re-run. See build-menus.sh.

struct Menu: Decodable {
    let slug: String
    let label: String
    let pdf: String
    let pages: [Int]
    let alt: String
}

let WIDTHS = [1200, 2400]      // srcset widths, longest edge in px
let JPEG_QUALITY = 0.82
let PAGE = "food-and-drink.html"
let START = "<!-- MENUS:START — generated by tools/build-menus.swift, do not edit by hand -->"
let END = "<!-- MENUS:END -->"

let root = URL(fileURLWithPath: CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : ".")
let menusDir = root.appendingPathComponent("menus")
let sourceDir = menusDir.appendingPathComponent("source")

func fail(_ message: String) -> Never {
    FileHandle.standardError.write("error: \(message)\n".data(using: .utf8)!)
    exit(1)
}

// ---------------------------------------------------------------- manifest

let manifestURL = menusDir.appendingPathComponent("menus.json")
guard let manifestData = try? Data(contentsOf: manifestURL) else {
    fail("cannot read \(manifestURL.path)")
}
guard let menus = try? JSONDecoder().decode([Menu].self, from: manifestData), !menus.isEmpty else {
    fail("menus.json is not a valid, non-empty list of menus")
}

// ---------------------------------------------------------------- rendering

// Renders one PDF page at the given longest-edge size and writes a JPEG.
func render(page: PDFPage, longestEdge: Int, to url: URL) -> Bool {
    let rect = page.bounds(for: .mediaBox)
    let scale = Double(longestEdge) / Double(max(rect.width, rect.height))
    let pxW = Int((Double(rect.width) * scale).rounded())
    let pxH = Int((Double(rect.height) * scale).rounded())

    guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: pxW, pixelsHigh: pxH,
                                     bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                     isPlanar: false, colorSpaceName: .calibratedRGB,
                                     bytesPerRow: 0, bitsPerPixel: 0),
          let ctx = NSGraphicsContext(bitmapImageRep: rep) else { return false }

    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = ctx
    let cg = ctx.cgContext
    // Menus are designed on white; without this, transparent areas go black in JPEG.
    cg.setFillColor(NSColor.white.cgColor)
    cg.fill(CGRect(x: 0, y: 0, width: pxW, height: pxH))
    cg.scaleBy(x: CGFloat(scale), y: CGFloat(scale))
    cg.translateBy(x: -rect.origin.x, y: -rect.origin.y)
    page.draw(with: .mediaBox, to: cg)
    NSGraphicsContext.restoreGraphicsState()

    guard let data = rep.representation(using: .jpeg,
                                        properties: [.compressionFactor: JPEG_QUALITY]) else { return false }
    do { try data.write(to: url) } catch { return false }
    return true
}

func escape(_ s: String) -> String {
    s.replacingOccurrences(of: "&", with: "&amp;")
        .replacingOccurrences(of: "<", with: "&lt;")
        .replacingOccurrences(of: ">", with: "&gt;")
        .replacingOccurrences(of: "\"", with: "&quot;")
}

var generated: Set<String> = []
var panels: [String] = []
var tabs: [String] = []
var options: [String] = []

for (index, menu) in menus.enumerated() {
    let pdfURL = sourceDir.appendingPathComponent(menu.pdf)
    guard let doc = PDFDocument(url: pdfURL) else {
        fail("cannot open \(pdfURL.path) — is the PDF named correctly in menus.json?")
    }

    var images: [String] = []

    for pageNumber in menu.pages {
        guard pageNumber >= 1, pageNumber <= doc.pageCount, let page = doc.page(at: pageNumber - 1) else {
            fail("\(menu.pdf) has \(doc.pageCount) page(s); menus.json asks for page \(pageNumber)")
        }

        var srcset: [String] = []
        var fallback = ""

        for width in WIDTHS {
            let name = "\(menu.slug)-\(pageNumber)-\(width).jpg"
            let out = menusDir.appendingPathComponent(name)
            guard render(page: page, longestEdge: width, to: out) else {
                fail("failed to render \(menu.pdf) page \(pageNumber) at \(width)px")
            }
            generated.insert(name)
            srcset.append("menus/\(name) \(width)w")
            if width == WIDTHS.first { fallback = "menus/\(name)" }
            let kb = ((try? Data(contentsOf: out))?.count ?? 0) / 1024
            print("  \(name)\t\(kb)KB")
        }

        // Only number the alt text when a menu actually spans several pages.
        let altText = menu.pages.count > 1
            ? "\(menu.alt) — page \(menu.pages.firstIndex(of: pageNumber)! + 1) of \(menu.pages.count)"
            : menu.alt

        let large = "menus/\(menu.slug)-\(pageNumber)-\(WIDTHS.last!).jpg"
        images.append("""
                <a class="menu-panel__page" href="\(large)" target="_blank" rel="noopener">
                  <img class="menu-panel__image" src="\(fallback)" srcset="\(srcset.joined(separator: ", "))" sizes="(max-width: 900px) 100vw, 1180px" alt="\(escape(altText))" loading="lazy">
                </a>
        """)
    }

    let isFirst = index == 0
    tabs.append("""
            <button class="menu-tab\(isFirst ? " active" : "")" type="button" data-menu="\(menu.slug)">\(escape(menu.label))</button>
    """)
    options.append("""
            <option value="\(menu.slug)">\(escape(menu.label))</option>
    """)
    // Every page image is already a link to its own full-size render, so the
    // button would be redundant — and on a multi-page menu it could only point
    // at one of them. Offer a hint instead.
    panels.append("""
          <div class="menu-panel\(isFirst ? " active" : "")" data-menu="\(menu.slug)">
    \(images.joined(separator: "\n"))
            <p class="menu-panel__hint">Tap any page to open it full size.</p>
          </div>
    """)
}

// ---------------------------------------------------------------- markup

let block = """
\(START)
      <div class="menu-tabs" role="tablist">
\(tabs.joined(separator: "\n"))
      </div>

      <select class="menu-select" aria-label="Choose menu">
\(options.joined(separator: "\n"))
      </select>

\(panels.joined(separator: "\n"))
      \(END)
"""

let pageURL = root.appendingPathComponent(PAGE)
guard var html = try? String(contentsOf: pageURL, encoding: .utf8) else {
    fail("cannot read \(pageURL.path)")
}
guard let startRange = html.range(of: START), let endRange = html.range(of: END) else {
    fail("\(PAGE) is missing the MENUS:START / MENUS:END markers")
}
guard startRange.lowerBound < endRange.lowerBound else {
    fail("\(PAGE) has the MENUS markers in the wrong order")
}

html.replaceSubrange(startRange.lowerBound..<endRange.upperBound, with: block)
do { try html.write(to: pageURL, atomically: true, encoding: .utf8) } catch {
    fail("cannot write \(pageURL.path): \(error)")
}

// Anything left in menus/ from an older run is now dead weight — say so rather
// than deleting, in case something else on the site still points at it.
let existing = (try? FileManager.default.contentsOfDirectory(atPath: menusDir.path)) ?? []
let stale = existing.filter { $0.hasSuffix(".jpg") || $0.hasSuffix(".png") }.filter { !generated.contains($0) }
if !stale.isEmpty {
    print("\nno longer referenced (safe to delete):")
    for file in stale.sorted() { print("  menus/\(file)") }
}

print("\n\(generated.count) image(s) from \(menus.count) menu(s); \(PAGE) updated.")
